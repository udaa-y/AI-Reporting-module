"""
app/utils/sql_safety.py
────────────────────────
SQL AST Validator — Node 5 in the LangGraph pipeline.

Uses sqlglot to parse the LLM-generated T-SQL and perform a series
of safety and correctness checks before the query ever reaches the
SQL Server. This is a hard security gate — no query bypasses it.

Checks performed (in order):
  1. Valid T-SQL syntax (sqlglot parse)
  2. Statement is a SELECT (blocks DROP, DELETE, UPDATE, INSERT, EXEC...)
  3. TOP N clause present — injects TOP {max_rows} if missing
  4. No stacked statements (semicolons used as separators)
  5. No SQL comment injection (-- or /* */)
  6. Referenced tables are in the allowed whitelist
  7. JOIN count sanity limit (≤ 8 JOINs)
"""

import logging
import re
from dataclasses import dataclass, field
from typing import Optional, Set

import sqlglot
import sqlglot.expressions as exp

from app.config import get_settings

logger = logging.getLogger(__name__)
settings = get_settings()

# SQL statements that are NEVER allowed
FORBIDDEN_STATEMENT_TYPES = (
    exp.Drop,
    exp.Delete,
    exp.Update,
    exp.Insert,
    exp.Create,
    exp.Alter,
    exp.Command,       # catches EXEC, EXECUTE, xp_ calls
    exp.Transaction,
    exp.Rollback,
    exp.Commit,
)

MAX_JOINS = 8


@dataclass
class ValidationResult:
    passed: bool
    errors: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)
    sanitized_sql: Optional[str] = None  # SQL after TOP N injection


def validate_sql(
    raw_sql: str,
    allowed_tables: Optional[Set[str]] = None,
    max_rows: Optional[int] = None,
) -> ValidationResult:
    """
    Parse and validate a T-SQL string generated by the LLM.

    Args:
        raw_sql:        The raw SQL string from the LLM.
        allowed_tables: Set of lowercase table names in the schema whitelist.
                        If None, table validation is skipped.
        max_rows:       Override max rows; defaults to settings.max_result_rows.

    Returns:
        ValidationResult with .passed, .errors, and .sanitized_sql
    """
    result = ValidationResult(passed=False)
    effective_max_rows = max_rows or settings.max_result_rows

    # ── Pre-parse sanity checks (no AST needed) ───────────────────────────────

    # Strip whitespace and remove trailing semicolons
    sql = raw_sql.strip().rstrip(";").strip()

    # Check for stacked statements (multiple ; within the body)
    if _has_multiple_statements(sql):
        result.errors.append(
            "Security: Multiple SQL statements detected. Only a single SELECT is allowed."
        )
        return result

    # Check for SQL comment injection patterns
    if _has_comment_injection(sql):
        result.errors.append(
            "Security: SQL comment injection detected (-- or /* */)."
        )
        return result

    # ── Parse the SQL with sqlglot (T-SQL / TSQL dialect) ────────────────────

    try:
        parsed = sqlglot.parse_one(sql, read="tsql")
    except sqlglot.errors.ParseError as exc:
        result.errors.append(f"SQL syntax error: {exc}")
        return result
    except Exception as exc:
        result.errors.append(f"SQL parse failure: {exc}")
        return result

    if parsed is None:
        result.errors.append("SQL parse returned empty result — invalid query.")
        return result

    # ── Check statement type ──────────────────────────────────────────────────

    if isinstance(parsed, FORBIDDEN_STATEMENT_TYPES):
        result.errors.append(
            f"Security: Statement type '{type(parsed).__name__}' is not allowed. "
            "Only SELECT statements are permitted."
        )
        return result

    if not isinstance(parsed, exp.Select):
        result.errors.append(
            f"Security: Expected SELECT statement, got '{type(parsed).__name__}'."
        )
        return result

    # ── Inject TOP N if missing ───────────────────────────────────────────────

    sanitized_sql = _inject_top_n(sql, parsed, effective_max_rows)

    # ── Table whitelist check ─────────────────────────────────────────────────

    if allowed_tables:
        referenced = _extract_table_names(parsed)
        unknown = referenced - {t.lower() for t in allowed_tables}
        if unknown:
            result.errors.append(
                f"Schema error: Unknown tables referenced: {', '.join(sorted(unknown))}. "
                "Only tables in the approved schema may be queried."
            )
            return result

    # ── JOIN complexity check ─────────────────────────────────────────────────

    join_count = len(list(parsed.find_all(exp.Join)))
    if join_count > MAX_JOINS:
        result.warnings.append(
            f"Query has {join_count} JOINs (limit is {MAX_JOINS}). "
            "Consider simplifying or it may be slow."
        )

    # ── All checks passed ─────────────────────────────────────────────────────

    result.passed = True
    result.sanitized_sql = sanitized_sql
    logger.info(
        "[Validator] SQL passed all checks. joins=%d, max_rows=%d",
        join_count, effective_max_rows,
    )
    return result


# ── Private Helpers ───────────────────────────────────────────────────────────

def _has_multiple_statements(sql: str) -> bool:
    """Detect semicolons used as statement separators (not inside strings)."""
    # Remove string literals first, then check for semicolons
    cleaned = re.sub(r"'[^']*'", "''", sql)
    return ";" in cleaned


def _has_comment_injection(sql: str) -> bool:
    """Detect SQL comment patterns that could be used for injection."""
    # Remove string literals before checking
    cleaned = re.sub(r"'[^']*'", "''", sql)
    return bool(re.search(r"(--|/\*|\*/)", cleaned))


def _extract_table_names(parsed: exp.Expression) -> set[str]:
    """Extract all table names referenced in the query (lowercase)."""
    tables = set()
    for table in parsed.find_all(exp.Table):
        if table.name:
            tables.add(table.name.lower())
    return tables


def _inject_top_n(sql: str, parsed: exp.Select, max_rows: int) -> str:
    """
    If the SELECT has no TOP clause, inject TOP {max_rows}.
    Returns the SQL string with TOP N added if needed.

    Example:
        "SELECT * FROM Orders" → "SELECT TOP 1000 * FROM Orders"
    """
    # Check if a limit or top expression already exists
    limit = parsed.find(exp.Limit)
    if limit is not None or re.search(r"\bTOP\s+\d+", sql, re.IGNORECASE):
        return sql  # Already has a TOP/LIMIT clause — respect the original

    # Inject TOP N after SELECT keyword
    select_pattern = re.compile(r"^(SELECT\s+)(DISTINCT\s+)?", re.IGNORECASE)
    match = select_pattern.match(sql)
    if match:
        prefix = match.group(0)
        rest = sql[match.end():]
        injected = f"{prefix}TOP {max_rows} {rest}"
        logger.debug("[Validator] Injected TOP %d into query.", max_rows)
        return injected

    return sql  # Fallback: return original if pattern fails
